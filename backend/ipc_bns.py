"""IPC -> BNS lookup for questions framed under the repealed Indian Penal Code.

Users still describe their cases by IPC section -- FIRs registered before 1 July 2024 carry IPC
numbers, and people keep using the old ones out of habit. The corpus is indexed by BNS section, so
an "IPC 420" question needs translating before retrieval and the answer needs to say which law
applies. The mapping itself is generated by build_ipc_bns_map.py from the BPR&D correspondence
table; this module only reads it.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import lru_cache
from typing import Any

from config import BASE_DIR

MAP_PATH = BASE_DIR / "ipc_bns_map.json"
# Every BNS section, not just the indexed extract; written by build_ipc_bns_map.py.
BNS_REFERENCE_PATH = BASE_DIR / "parsed" / "bns_reference_chunks.jsonl"
BNS_SOURCE_FILE = "cyber/bharatiya_nyaya_sanhita_2023.pdf"

# Which law governs an IPC-era offence. Quotes BNS 358 rather than paraphrasing it; the date is
# from the BPR&D table's row for BNS 358.
TRANSITION_NOTE = (
    "The IPC was repealed by section 358(1) of the BNS, from 1 July 2024 (date as recorded in the "
    "BPR&D correspondence table). Under BNS 358(2), the repeal does not affect \"any penalty, or "
    "punishment incurred in respect of any offences committed against the Code so repealed\", and "
    "proceedings for them \"may be instituted, continued or enforced ... as if that Code had not been "
    "repealed\". So an offence committed before 1 July 2024 is still dealt with under the IPC, and one "
    "committed on or after that date falls under the BNS. Source: BNS section 358 (official BNS text)."
)

# Digit lookarounds stop "Indian Penal Code, 1860" reading as IPC section 186.
_SECTION = r"(?<!\d)\d{1,3}(?!\d)(?:-?[A-Za-z]{1,2})?(?:\s*\(\d+\))*"
_JOINER = r"\s*(?:,|/|&|\band\b|\bor\b|\br/w\b|\bread\s+with\b)\s*"
_SECTION_RUN = rf"{_SECTION}(?:{_JOINER}{_SECTION})*"
_IPC_NAME = r"(?:I\.\s?P\.\s?C\.?|\bIPC\b|(?:the\s+)?Indian\s+Penal\s+Code(?:,?\s*1860)?|\bPenal\s+Code\b)"
_SECTION_WORD = r"(?:sections?|secs?\.?|ss?\.|u/s\.?|under\s+section)"

# "420 IPC", "u/s 354D/506/509 IPC", "sections 420 and 406 of the Indian Penal Code"
_RUN_BEFORE_IPC = re.compile(rf"(?:{_SECTION_WORD}\s*)?({_SECTION_RUN})\s*(?:of\s+(?:the\s+)?)?{_IPC_NAME}", re.I)
# "IPC 420", "IPC section 354D", "IPC sections 420, 406"
_RUN_AFTER_IPC = re.compile(rf"{_IPC_NAME}\s*,?\s*(?:{_SECTION_WORD}\s*)?({_SECTION_RUN})", re.I)
_SECTION_TOKEN = re.compile(rf"{_SECTION}")

# A question that is only asking where an IPC section went ("what is IPC 302 now?", "IPC 420 in
# BNS") rather than describing a case and asking what to do about it.
_LOOKUP_CUE_RE = re.compile(
    r"\b(bns|bharatiya|nyaya|sanhita|new (?:law|code|section|criminal laws?)|now|equivalent|replaced|"
    r"replacement|correspond\w*|changed?|became|still|what (?:is|does|was|are)|meaning|means|which section)\b",
    re.I,
)
_CASE_HELP_RE = re.compile(
    r"\b(what (?:should|can|do) i|how (?:do|can|should) i|help me|can i|should i|my rights|bail|lawyer|"
    r"advocate|complaint|report)\b",
    re.I,
)
LOOKUP_MAX_WORDS = 25
BARE_CITATION_MAX_WORDS = 6


@dataclass(frozen=True)
class IpcMapping:
    ipc_section: str
    ipc_title: str | None
    status: str
    bns: tuple[dict[str, Any], ...]
    notes: tuple[dict[str, str], ...]

    @property
    def bns_sections(self) -> list[str]:
        return [entry["section"] for entry in self.bns]


@lru_cache(maxsize=1)
def load_map() -> dict[str, Any]:
    return json.loads(MAP_PATH.read_text(encoding="utf-8"))


def bns_commencement_date() -> str:
    return load_map()["bns_commencement_date"]


def normalize_section(token: str) -> str:
    """'354-d' -> '354D', '376(2)' -> '376'. Subsections are dropped: the map is keyed by section."""
    token = re.sub(r"\s*\(\d+\)", "", token)
    return token.replace("-", "").replace(" ", "").upper()


def find_ipc_sections(text: str) -> list[str]:
    """IPC section numbers the text cites, in order of first mention, limited to real IPC sections.

    Only numbers attached to an explicit IPC mention count: a bare "section 420" could be any Act."""
    known = load_map()["ipc_to_bns"]
    first_seen: dict[str, int] = {}
    for pattern in (_RUN_BEFORE_IPC, _RUN_AFTER_IPC):
        for match in pattern.finditer(text):
            for token in _SECTION_TOKEN.finditer(match.group(1)):
                section = normalize_section(token.group(0))
                position = match.start(1) + token.start()
                if section in known and position < first_seen.get(section, len(text)):
                    first_seen[section] = position
    return sorted(first_seen, key=first_seen.__getitem__)


def is_lookup_question(text: str) -> bool:
    """True for a short "where did this IPC section go" question, which is answered from the map and
    the BNS text directly. Anything describing a case or asking what to do goes through the normal
    pipeline, which still attaches the mapping."""
    if not find_ipc_sections(text):
        return False
    words = len(re.findall(r"\w+", text))
    if words <= BARE_CITATION_MAX_WORDS:
        return True
    return words <= LOOKUP_MAX_WORDS and bool(_LOOKUP_CUE_RE.search(text)) and not _CASE_HELP_RE.search(text)


@lru_cache(maxsize=1)
def _bns_reference() -> tuple[dict[str, Any], ...]:
    if not BNS_REFERENCE_PATH.exists():
        return ()
    with BNS_REFERENCE_PATH.open(encoding="utf-8") as handle:
        return tuple(json.loads(line) for line in handle if line.strip())


def bns_reference_chunks(sections: set[str] | frozenset[str]) -> list[dict[str, Any]]:
    """Every chunk of the given base BNS sections ("318", "63"), in section order."""
    chunks = [item for item in _bns_reference() if item.get("section_number") in sections]
    return sorted(chunks, key=lambda item: (int(re.match(r"\d+", item["section_number"]).group(0)), item.get("provision_chunk_index") or 0))


def lookup(ipc_section: str) -> IpcMapping | None:
    entry = load_map()["ipc_to_bns"].get(normalize_section(ipc_section))
    if entry is None:
        return None
    return IpcMapping(
        ipc_section=normalize_section(ipc_section),
        ipc_title=entry.get("ipc_title"),
        status=entry["status"],
        bns=tuple(entry.get("bns", [])),
        notes=tuple(entry.get("notes", [])),
    )


def mappings_for_text(text: str) -> list[IpcMapping]:
    return [mapping for mapping in (lookup(section) for section in find_ipc_sections(text)) if mapping]


def mapping_note(mapping: IpcMapping) -> str:
    """One plain-language line per IPC section, for the answer prompt and offline responses.

    Each line says where it comes from: the government table, the BNS text, or neither."""
    title = f" ({mapping.ipc_title})" if mapping.ipc_title else ""
    label = f"IPC {mapping.ipc_section}{title}"
    notes = " ".join(note["text"] for note in mapping.notes)
    if mapping.status == "repealed_before_bns":
        return f"{label} had already been repealed before the BNS came into force, so it has no BNS equivalent. {notes}".strip()
    if mapping.status == "no_bns_equivalent":
        return f"{label} has no equivalent in the BNS. {notes}".strip()
    parts = []
    for entry in mapping.bns:
        summary = entry.get("change_summary", "").strip().rstrip(".")
        if entry.get("source") != "bprd_table":
            detail = summary
        elif entry.get("change_type") == "unchanged":
            detail = "renumbered; the offence itself is unchanged. Source: BPR&D correspondence table"
        else:
            detail = f"changed: {summary}. Source: BPR&D correspondence table"
        parts.append(f"BNS {entry['section']} ({detail})")
    return f"{label} → {'; '.join(parts)}."


@lru_cache(maxsize=256)
def mapped_bns_sections(text: str) -> frozenset[str]:
    """Base BNS section numbers ("318", "351") that the IPC sections cited in `text` map to.
    Cached because the retrieval reranker asks once per candidate chunk with the same question."""
    sections = set()
    for mapping in mappings_for_text(text):
        for entry in mapping.bns:
            base = re.match(r"\d+", entry["section"])
            if base:
                sections.add(base.group(0))
    return frozenset(sections)


def with_ipc_citations(search_text: str, mappings: list[IpcMapping]) -> str:
    """Re-attach IPC citations the user typed but an upstream summary dropped, so retrieval sees them."""
    present = set(find_ipc_sections(search_text))
    missing = [mapping.ipc_section for mapping in mappings if mapping.ipc_section not in present]
    if not missing:
        return search_text
    return f"{search_text} ({', '.join(f'IPC {section}' for section in missing)})"


def response_payload(mappings: list[IpcMapping]) -> dict[str, Any] | None:
    """The mapping as shown to the user. Built from the map alone, never by the answer model, so the
    claim verifier cannot strip it and the model cannot alter it."""
    if not mappings:
        return None
    return {
        "sections": [
            {
                "ipc_section": mapping.ipc_section,
                "ipc_title": mapping.ipc_title,
                "status": mapping.status,
                "bns_sections": mapping.bns_sections,
                "sources": sorted({item["source"] for item in [*mapping.bns, *mapping.notes]}),
                "note": mapping_note(mapping),
            }
            for mapping in mappings
        ],
        "transition_note": TRANSITION_NOTE,
    }


def prompt_block(mappings: list[IpcMapping]) -> str:
    if not mappings:
        return ""
    lines = "\n".join(f"- {mapping_note(mapping)}" for mapping in mappings)
    return f"{lines}\n- {TRANSITION_NOTE}"


def retrieval_terms(mappings: list[IpcMapping]) -> str:
    """Extra query text so retrieval finds the BNS provisions an IPC question is really about."""
    terms: list[str] = []
    for mapping in mappings:
        for entry in mapping.bns:
            base = re.match(r"\d+", entry["section"])
            subject = (entry.get("subject") or "").rstrip(".")
            if base:
                terms.append(f"Bharatiya Nyaya Sanhita Section {base.group(0)} {subject}".strip())
    return " ".join(dict.fromkeys(terms))
